#!/usr/bin/env bash
# One-time database preparation for the HSG staging stack.
# Runs migrations with the owner role, then creates the non-owner runtime role
# the tenant pool uses (RLS applies to it because it owns nothing and is not a
# member of the owner).
set -euo pipefail

cd "$(dirname "$0")/.."
set -a
# shellcheck disable=SC1091
. ./.env
set +a
# LLM_ENCRYPTION_KEY lives in the runtime env file, not the compose file. Only
# this one key is read: hsg.env holds values that are not shell-safe.
LLM_ENCRYPTION_KEY="$(sed -n 's/^LLM_ENCRYPTION_KEY=//p' hsg.env | tail -1)"

echo "==> waiting for postgres"
for _ in $(seq 1 60); do
  if docker compose exec -T db pg_isready -U hsg -d hsg >/dev/null 2>&1; then break; fi
  sleep 1
done

echo "==> applying migrations (owner role)"
# --entrypoint is required: the image's ENTRYPOINT is the API, so a bare
# `api /app/migrate up` would run `/app/api /app/migrate up`.
docker compose run --rm --no-deps --entrypoint /app/migrate \
  -e DB_DSN="postgres://hsg:${POSTGRES_PASSWORD}@db:5432/hsg?sslmode=disable" \
  api up

echo "==> creating embedding worker role"
# The worker login only inherits hsg_embedding_worker, never the executor.
# ValidateRole requires zero direct table privileges on any public table, so
# only the role membership is granted here.
docker compose exec -T -e PGPASSWORD="$POSTGRES_PASSWORD" db \
  psql -v ON_ERROR_STOP=1 -U hsg -d hsg \
  -v worker_password="$EMBEDDING_WORKER_DB_PASSWORD" <<'SQL'
\set ON_ERROR_STOP on
SELECT format('CREATE ROLE hsg_embedding_worker LOGIN PASSWORD %L', :'worker_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hsg_embedding_worker')
\gexec
SELECT format('ALTER ROLE hsg_embedding_worker WITH LOGIN PASSWORD %L', :'worker_password')
\gexec
ALTER ROLE hsg_embedding_worker NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION NOINHERIT;
GRANT USAGE ON SCHEMA public TO hsg_embedding_worker;
-- The worker only executes the SECURITY DEFINER functions owned by the
-- executor role; those functions hold the row-level locks themselves.
GRANT EXECUTE ON FUNCTION knowledge_embedding_claim(), knowledge_embedding_read(uuid, bigint), knowledge_embedding_commit(uuid, bigint, jsonb), knowledge_embedding_fail(uuid, bigint, text), knowledge_embedding_worker_config(uuid, bigint) TO hsg_embedding_worker;
SQL

echo "==> bootstrapping embedding config (bge-m3, self-hosted)"
# The credential is sealed with AES-GCM and an AAD that binds the endpoint and
# the profile fingerprint; psql cannot produce it, so it is generated by the
# migrate command with the same AAD as handlers/embeddingCredential.
docker compose run --rm --no-deps --entrypoint /app/migrate \
  -e DB_DSN="postgres://hsg:${POSTGRES_PASSWORD}@db:5432/hsg?sslmode=disable" \
  -e LLM_ENCRYPTION_KEY="$LLM_ENCRYPTION_KEY" \
  -e EMBEDDING_ENDPOINT="http://embedding:8080/v1/embeddings" \
  -e EMBEDDING_REVISION="$EMBEDDING_MODEL_REVISION" \
  -e EMBEDDING_API_KEY="$EMBEDDING_API_KEY" \
  api seed-embedding

echo "==> creating tenant runtime role"
# The password is interpolated by psql (\set + :'var'), not by a DO block:
# psql variables are not visible inside dollar-quoted PL/pgSQL bodies.
docker compose exec -T -e PGPASSWORD="$POSTGRES_PASSWORD" db \
  psql -v ON_ERROR_STOP=1 -U hsg -d hsg \
  -v tenant_password="$TENANT_DB_PASSWORD" <<'SQL'
\set ON_ERROR_STOP on
SELECT format('CREATE ROLE hsg_tenant LOGIN PASSWORD %L', :'tenant_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hsg_tenant')
\gexec
SELECT format('ALTER ROLE hsg_tenant WITH LOGIN PASSWORD %L', :'tenant_password')
\gexec
ALTER ROLE hsg_tenant NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION;
GRANT USAGE ON SCHEMA public TO hsg_tenant;
GRANT SELECT, INSERT, UPDATE, DELETE ON tenants, tenant_memberships, tenant_audit_events TO hsg_tenant;
GRANT SELECT, INSERT, UPDATE, DELETE ON ai_chat_sessions, ai_chat_messages, ai_chat_token_usage, ai_chat_tool_logs TO hsg_tenant;
GRANT SELECT, INSERT ON platform_chat_token_usages TO hsg_tenant;
GRANT SELECT, INSERT, UPDATE ON tenant_token_balances TO hsg_tenant;
GRANT SELECT, INSERT ON tenant_token_topups, tenant_token_usages TO hsg_tenant;
GRANT SELECT ON users TO hsg_tenant;
-- Append-only: the runtime role may read and append audit rows, never edit or
-- delete them. The table's trigger rejects UPDATE/DELETE even for the owner.
GRANT SELECT, INSERT ON audit_logs TO hsg_tenant;
-- Knowledge base: row-level security decides who may read or write which rows.
GRANT SELECT, INSERT, UPDATE, DELETE ON knowledge_documents, knowledge_chunks, knowledge_categories TO hsg_tenant;
-- Embedding: the HTTP runtime reads the admin config singleton, per-document
-- indexing status, and semantic vectors for hybrid search. RLS keeps every
-- read inside the pinned tenant (or global) scope; status/retry are SECURITY
-- DEFINER and re-check membership themselves.
GRANT SELECT ON knowledge_embedding_config, knowledge_embedding_profiles, knowledge_embedding_jobs, knowledge_chunk_embeddings TO hsg_tenant;
GRANT EXECUTE ON FUNCTION knowledge_embedding_status(uuid, uuid), knowledge_embedding_retry(uuid, uuid) TO hsg_tenant;
-- Knowledge usage: the runtime role may read and append the metrics log, never
-- edit or delete it. RLS keeps every read inside the pinned scope.
GRANT SELECT, INSERT ON knowledge_document_usage_log TO hsg_tenant;
SQL

echo "==> done"